export type MigrationStatus = 
  | 'keepAsIsTemporarily' // Bleibt vorerst unverändert im Legacy-System
  | 'migrate'             // Gut strukturiert, kann in modulare 1:1-Test-Engine übernommen werden
  | 'merge'               // Stark überlappend/doppelt mit anderem Test -> zusammenführen
  | 'redesign'            // Inhaltlich sinnvoll, aber Aufgaben, UI oder Bewertungslogik müssen neu gebaut werden
  | 'retire';             // Redundant, durch Pilot/bessere Tests ersetzt oder fachlich ungeeignet

export type UiQuality = 'good' | 'usable' | 'poor';
export type ScoringQuality = 'good' | 'needsReview' | 'problematic';
export type MigrationPriority = 'high' | 'medium' | 'low';

